create table if not exists public.clinical_notes (
  id bigint generated by default as identity primary key,
  appointment_id bigint not null references public.appointments(id) on delete cascade,
  veterinarian_id uuid not null references public.profiles(id) on delete restrict,
  diagnosis text not null,
  treatment text not null,
  observations text,
  created_at timestamptz not null default now()
);

create index if not exists clinical_notes_appointment_id_idx on public.clinical_notes(appointment_id);
create index if not exists clinical_notes_veterinarian_id_idx on public.clinical_notes(veterinarian_id);

alter table public.clinical_notes enable row level security;

drop policy if exists clinical_notes_staff_read on public.clinical_notes;
create policy clinical_notes_staff_read on public.clinical_notes
  for select to authenticated
  using (public.current_app_role() in ('ADMIN', 'VET', 'RECEPTIONIST'));

drop policy if exists clinical_notes_staff_insert on public.clinical_notes;
create policy clinical_notes_staff_insert on public.clinical_notes
  for insert to authenticated
  with check (public.current_app_role() in ('ADMIN', 'VET'));
