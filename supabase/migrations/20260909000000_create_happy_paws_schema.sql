drop policy if exists profiles_self_select on public.profiles;
create policy profiles_self_select on public.profiles
  for select to authenticated
  using (id = auth.uid() or public.current_app_role() in ('ADMIN', 'VET', 'RECEPTIONIST'));

drop policy if exists profiles_admin_update on public.profiles;
create policy profiles_admin_update on public.profiles
  for update to authenticated
  using (public.current_app_role() = 'ADMIN')
  with check (public.current_app_role() = 'ADMIN');

drop policy if exists owners_read on public.owners;
create policy owners_read on public.owners
  for select to authenticated
  using (auth_user_id = auth.uid() or public.current_app_role() in ('ADMIN', 'VET', 'RECEPTIONIST'));

drop policy if exists owners_staff_write on public.owners;
create policy owners_staff_write on public.owners
  for all to authenticated
  using (public.current_app_role() in ('ADMIN', 'RECEPTIONIST'))
  with check (public.current_app_role() in ('ADMIN', 'RECEPTIONIST'));

drop policy if exists pets_read on public.pets;
create policy pets_read on public.pets
  for select to authenticated
  using (
    exists (select 1 from public.owners o where o.id = owner_id and o.auth_user_id = auth.uid())
    or public.current_app_role() in ('ADMIN', 'VET', 'RECEPTIONIST')
  );

drop policy if exists pets_staff_write on public.pets;
create policy pets_staff_write on public.pets
  for all to authenticated
  using (public.current_app_role() in ('ADMIN', 'RECEPTIONIST'))
  with check (public.current_app_role() in ('ADMIN', 'RECEPTIONIST'));

drop policy if exists services_authenticated_read on public.services;
create policy services_authenticated_read on public.services
  for select to authenticated using (true);

drop policy if exists services_admin_write on public.services;
create policy services_admin_write on public.services
  for all to authenticated
  using (public.current_app_role() = 'ADMIN')
  with check (public.current_app_role() = 'ADMIN');

drop policy if exists appointments_read on public.appointments;
