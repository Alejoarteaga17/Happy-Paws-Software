  for select to authenticated
  using (
    exists (
      select 1 from public.pets p
      join public.owners o on o.id = p.owner_id
      where p.id = pet_id and o.auth_user_id = auth.uid()
    )
    or public.current_app_role() in ('ADMIN', 'VET', 'RECEPTIONIST')
  );

