create extension if not exists pgcrypto;

do $$
begin
  create type public.user_role as enum ('ADMIN', 'VET', 'RECEPTIONIST', 'OWNER');
exception
  when duplicate_object then null;
end $$;

do $$
begin
  create type public.appointment_status as enum ('SCHEDULED', 'COMPLETED', 'CANCELLED');
exception
  when duplicate_object then null;
end $$;

do $$
begin
  create type public.vaccination_status as enum ('ADMINISTERED', 'PENDING', 'OVERDUE');
exception
  when duplicate_object then null;
end $$;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null unique,
  full_name text not null,
  role public.user_role not null default 'OWNER',
  created_at timestamptz not null default now()
);

create table if not exists public.owners (
  id bigint generated by default as identity primary key,
  auth_user_id uuid unique references auth.users(id) on delete set null,
  full_name text not null,
  phone text not null,
  email text,
  address text,
  created_at timestamptz not null default now()
);

create table if not exists public.pets (
  id bigint generated by default as identity primary key,
  owner_id bigint not null references public.owners(id) on delete cascade,
  pet_tag text not null unique,
  name text not null,
  species text not null,
  breed text,
  birth_date date,
  weight numeric(5, 2) check (weight is null or weight > 0),
  created_at timestamptz not null default now()
);

create table if not exists public.services (
  id bigint generated by default as identity primary key,
  name text not null unique,
  description text,
  price_cents integer not null default 0 check (price_cents >= 0)
);

create table if not exists public.appointments (
  id bigint generated by default as identity primary key,
  pet_id bigint not null references public.pets(id) on delete cascade,
  vet_id uuid references public.profiles(id) on delete set null,
  scheduled_at timestamptz not null,
  reason text not null,
  notes text,
  status public.appointment_status not null default 'SCHEDULED',
  created_at timestamptz not null default now()
);

create table if not exists public.appointment_services (
  appointment_id bigint not null references public.appointments(id) on delete cascade,
  service_id bigint not null references public.services(id) on delete restrict,
  primary key (appointment_id, service_id)
);

create table if not exists public.vaccinations (
  id bigint generated by default as identity primary key,
  pet_id bigint not null references public.pets(id) on delete cascade,
  appointment_id bigint references public.appointments(id) on delete set null,
  vaccine_name text not null,
  administered_at date not null,
  next_due_date date not null,
  status public.vaccination_status not null default 'PENDING',
  created_at timestamptz not null default now(),
  check (next_due_date >= administered_at)
);

create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  actor_user_id uuid references auth.users(id) on delete set null,
  action text not null,
  entity_name text not null,
  entity_id text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists pets_owner_id_idx on public.pets(owner_id);
create index if not exists pets_name_idx on public.pets(lower(name));
create index if not exists pets_pet_tag_idx on public.pets(lower(pet_tag));
create index if not exists owners_phone_idx on public.owners(phone);
create index if not exists appointments_scheduled_at_idx on public.appointments(scheduled_at);
create index if not exists appointments_pet_id_idx on public.appointments(pet_id);
create index if not exists vaccinations_pet_id_idx on public.vaccinations(pet_id);
create index if not exists vaccinations_next_due_date_idx on public.vaccinations(next_due_date);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, email, full_name, role)
  values (
    new.id,
    coalesce(new.email, ''),
    coalesce(new.raw_user_meta_data ->> 'full_name', split_part(coalesce(new.email, 'Usuario'), '@', 1)),
    'OWNER'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

create or replace function public.current_app_role()
returns public.user_role
language sql
stable
security definer
set search_path = public
as $$
  select role from public.profiles where id = auth.uid();
$$;

